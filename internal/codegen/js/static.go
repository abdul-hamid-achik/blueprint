func (g *Generator) genEnvExample(secrets []*ast.Secret, envs []*ast.Env, extraEnvVars ...string) codegen.OutputFile {
	var b strings.Builder
	b.WriteString("# Generated by Blueprint — fill in your values\n\n")
	declared := make(map[string]bool)
	wroteInfraLine := false
	for _, s := range secrets {
		declared[s.Name] = true
		fmt.Fprintf(&b, "%s=\n", s.Name)
		wroteInfraLine = true
	}
	// Seed the dedupe set with user env declarations BEFORE adding extra
	// infra vars so a user `env DATABASE_URL { ... }` doesn't produce a
	// duplicate line in .env.example.
	for _, e := range envs {
		declared[e.Name] = true
	}
	// Extra infra env vars (e.g., REDIS_URL, DATABASE_URL) that aren't already
	// declared as secrets or envs — keep .env.example in sync with env.ts.
	for _, name := range extraEnvVars {
		if declared[name] {
			continue
		}
		declared[name] = true
		fmt.Fprintf(&b, "%s=\n", name)
		wroteInfraLine = true
	}
	if wroteInfraLine && len(envs) > 0 {
		b.WriteString("\n")
	}
	for _, e := range envs {
		val := exprToString(e.Value)
		fmt.Fprintf(&b, "%s=%s\n", e.Name, val)
	}
	return codegen.OutputFile{Path: ".env.example", Content: []byte(b.String())}
}

func (g *Generator) genEnvTS(secrets []*ast.Secret, envs []*ast.Env, extraEnvVars ...string) codegen.OutputFile {
	var b strings.Builder
	b.WriteString(fileHeader(g.sourceFile))
	b.WriteString("import { z } from 'zod';\nimport 'dotenv/config';\n\n")
	b.WriteString("const envSchema = z.object({\n")

	// Track which env vars are already declared by secrets/envs to avoid duplicates
	declared := make(map[string]bool)
	for _, s := range secrets {
		declared[s.Name] = true
		req := ".optional()"
		if s.Required {
			req = ""
		}
		fmt.Fprintf(&b, "  %s: z.string()%s,\n", s.Name, req)
	}
	// Seed the dedupe set with user env declarations BEFORE adding extra
	// infra vars (REDIS_URL, DATABASE_URL, ...) so a user `env DATABASE_URL
	// { ... }` is not also emitted as a bare z.string(), producing a
	// duplicate key (TS1117).
	for _, e := range envs {
		declared[e.Name] = true
	}
	for _, name := range extraEnvVars {
		if !declared[name] {
			declared[name] = true
			fmt.Fprintf(&b, "  %s: z.string(),\n", name)
		}
	}
	for _, e := range envs {
		zodType := "z.string()"
		defaultVal := exprToJS(e.Value)
		switch e.Value.(type) {
		case *ast.IntLit, *ast.FloatLit, *ast.SizeLit:
			zodType = "z.coerce.number()"
		case *ast.ListExpr:
			// List env vars: store as JSON string, parse on load
			zodType = "z.string().transform((v: string) => v.split(','))"
			// Convert list to comma-separated string default
			list := e.Value.(*ast.ListExpr)
			parts := make([]string, len(list.Elements))
			for i, el := range list.Elements {
				parts[i] = exprToString(el)
			}
			defaultVal = fmt.Sprintf(`"%s"`, strings.Join(parts, ","))
		case *ast.BinaryExpr:
			// Arithmetic expressions in env defaults are numeric
			zodType = "z.coerce.number()"
		case *ast.StringLit:
			// String default needs to be quoted
			defaultVal = fmt.Sprintf(`"%s"`, exprToString(e.Value))
		}
		fmt.Fprintf(&b, "  %s: %s.default(%s),\n", e.Name, zodType, defaultVal)
	}
	b.WriteString("});\n\n")
	b.WriteString("export const env = envSchema.parse(process.env);\n")

	return codegen.OutputFile{Path: "src/lib/env.ts", Content: []byte(b.String())}
}

