func (g *Generator) genPackageJSON(bp *ast.Blueprint, hasDB, hasCache, hasStorage, hasQueue, hasEndpoints, hasWS bool) codegen.OutputFile {
	name := bp.Name

	deps := map[string]string{
		"hono":              "^4.6.0",
		"@hono/node-server": "^1.13.0",
		"zod":               "^3.23.0",
		"dotenv":            "^16.4.0",
	}
	if hasEndpoints {
		deps["@hono/zod-validator"] = "^0.4.2"
	}
	if hasDB {
		deps["drizzle-orm"] = "^0.45.2"
		deps["pg"] = "^8.13.0"
	}
	if hasCache {
		// bullmq@5.30+ peer-requires redis>=5.0.0; keep these in lockstep
		// so `npm install` on a generated project doesn't ERESOLVE.
		deps["redis"] = "^5.0.0"
	}
	if hasStorage {
		deps["@aws-sdk/client-s3"] = "^3.700.0"
	}
	if hasQueue {
		deps["bullmq"] = "^5.30.0"
	}
	if hasWS {
		deps["@hono/node-ws"] = "^1.0.0"
	}
	if g.reactQuery {
		deps["@tanstack/react-query"] = "^5.59.20"
		deps["react"] = "^18.3.1"
	}

	devDeps := map[string]string{
		"typescript":  "^5.7.0",
		"tsx":         "^4.19.0",
		"@types/node": "^22.0.0",
		"@types/pg":   "^8.11.0",
		"vitest":      "^4.1.10",
	}
	if hasDB {
		devDeps["drizzle-kit"] = "^0.31.10"
	}
	if (g.genTests || g.propertyTests) && hasDB {
		devDeps["@electric-sql/pglite"] = "^0.2.0"
	}
	if g.propertyTests {
		devDeps["fast-check"] = "^3.23.2"
	}
	if g.reactQuery {
		devDeps["@types/react"] = "^18.3.12"
	}

	var b strings.Builder
	b.WriteString("{\n")
	fmt.Fprintf(&b, "  \"name\": %s,\n", fmt.Sprintf("%q", name))
	b.WriteString(`  "version": "0.1.0",` + "\n")
	b.WriteString(`  "private": true,` + "\n")
	b.WriteString(`  "type": "module",` + "\n")
	b.WriteString(`  "scripts": {` + "\n")
	fmt.Fprintf(&b, `    "start": "tsx src/index.ts",`+"\n")
	fmt.Fprintf(&b, `    "dev": "tsx watch src/index.ts",`+"\n")
	b.WriteString(`    "build": "tsc",` + "\n")
	b.WriteString(`    "test": "vitest run",` + "\n")
	b.WriteString(`    "test:watch": "vitest"` + "\n")
	b.WriteString("  },\n")

	// Dependencies — sorted for deterministic output
	b.WriteString(`  "dependencies": {` + "\n")
	depKeys := sortedKeys(deps)
	for i, k := range depKeys {
		comma := ","
		if i == len(depKeys)-1 {
			comma = ""
		}
		fmt.Fprintf(&b, `    "%s": "%s"%s`+"\n", k, deps[k], comma)
	}
	b.WriteString("  },\n")

	// Dev dependencies — sorted for deterministic output
	b.WriteString(`  "devDependencies": {` + "\n")
	devKeys := sortedKeys(devDeps)
	for i, k := range devKeys {
		comma := ","
		if i == len(devKeys)-1 {
			comma = ""
		}
		fmt.Fprintf(&b, `    "%s": "%s"%s`+"\n", k, devDeps[k], comma)
	}
	b.WriteString("  }\n")
	b.WriteString("}\n")

	return codegen.OutputFile{Path: "package.json", Content: []byte(b.String())}
}

