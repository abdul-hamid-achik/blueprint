func (g *Generator) genI18n(locales []*ast.Locale, translations []*ast.Translation) codegen.OutputFile {
	var b strings.Builder
	b.WriteString(fileHeader(g.sourceFile))
	b.WriteString("export const locales = [")
	for i, loc := range locales {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", loc.Code)
	}
	b.WriteString("] as const;\n")
	defaultLocale := ""
	for _, loc := range locales {
		if loc.Default {
			defaultLocale = loc.Code
			break
		}
	}
	if defaultLocale == "" && len(locales) > 0 {
		defaultLocale = locales[0].Code
	}
	fmt.Fprintf(&b, "export const defaultLocale = %q;\n", defaultLocale)
	fallbackParts := make([]string, 0, len(locales))
	for _, loc := range locales {
		fallback := loc.Fallback
		if fallback == "" {
			fallback = loc.Code
		}
		fallbackParts = append(fallbackParts, fmt.Sprintf("%q: %q", loc.Code, fallback))
	}
	fmt.Fprintf(&b, "export const localeFallbacks = { %s } as const;\n", strings.Join(fallbackParts, ", "))
	namespaceParts := make([]string, 0, len(translations))
	valueParts := make([]string, 0, len(translations))
	for _, tr := range translations {
		var keyParts []string
		for _, key := range tr.Keys {
			keyParts = append(keyParts, fmt.Sprintf("%q", key))
		}
		namespaceParts = append(namespaceParts, fmt.Sprintf("%s: [%s]", toCamelCase(tr.Name), strings.Join(keyParts, ", ")))
		bundleParts := make([]string, 0, len(tr.Bundles))
		for _, bundle := range tr.Bundles {
			localized := make([]string, 0, len(bundle.Values))
			for _, kv := range bundle.Values {
				localized = append(localized, fmt.Sprintf("%q: %s", kv.Key, exprToJS(kv.Value)))
			}
			bundleParts = append(bundleParts, fmt.Sprintf("%q: { %s }", bundle.Locale, strings.Join(localized, ", ")))
		}
		valueParts = append(valueParts, fmt.Sprintf("%s: { %s }", toCamelCase(tr.Name), strings.Join(bundleParts, ", ")))
	}
	fmt.Fprintf(&b, "export const translationNamespaces = { %s } as const;\n", strings.Join(namespaceParts, ", "))
	fmt.Fprintf(&b, "export const translationValues = { %s } as const;\n", strings.Join(valueParts, ", "))
	b.WriteString("export type LocaleCode = (typeof locales)[number];\n")
	b.WriteString("export type TranslationNamespace = keyof typeof translationNamespaces;\n")
	return codegen.OutputFile{Path: "src/lib/i18n.ts", Content: []byte(b.String())}
}

func (g *Generator) genStateLib(states []*ast.StateMachine) codegen.OutputFile {
	var b strings.Builder
	b.WriteString(fileHeader(g.sourceFile))
	b.WriteString("export class InvalidTransitionError extends Error {\n")
	b.WriteString("  constructor(public machine: string, public from: string, public to: string) {\n")
	b.WriteString("    super(`Invalid transition for ${machine}: ${from} -> ${to}`);\n")
	b.WriteString("    this.name = 'InvalidTransitionError';\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")
	for _, sm := range states {
		name := toPascalCase(sm.Name)
		parts := make([]string, 0, len(sm.States))
		for _, state := range sm.States {
			nexts := make([]string, 0)
			for _, tr := range sm.Transitions {
				if tr.From == state {
					nexts = append(nexts, fmt.Sprintf("%q", tr.To))
				}
			}
			parts = append(parts, fmt.Sprintf("  %s: [%s]", state, strings.Join(nexts, ", ")))
		}
		fmt.Fprintf(&b, "export const %sTransitions = {\n%s\n} as const;\n", name, strings.Join(parts, ",\n"))
		fmt.Fprintf(&b, "export function canTransition%s(from: string, to: string): boolean {\n", name)
		fmt.Fprintf(&b, "  return ((%sTransitions as any)[from] ?? []).includes(to);\n", name)
		b.WriteString("}\n")
		fmt.Fprintf(&b, "export function transition%s<T extends string>(from: T, to: T): T {\n", name)
		fmt.Fprintf(&b, "  if (!canTransition%s(from, to)) throw new InvalidTransitionError(%q, from, to);\n", name, sm.Name)
		b.WriteString("  return to;\n")
		b.WriteString("}\n\n")
	}
	return codegen.OutputFile{Path: "src/lib/state.ts", Content: []byte(b.String())}
}

func (g *Generator) genAnalyticsLib(analytics []*ast.Analytics) codegen.OutputFile {
	var b strings.Builder
	b.WriteString(fileHeader(g.sourceFile))
	namespaceParts := make([]string, 0, len(analytics))
	sinkParts := make([]string, 0, len(analytics))
	for _, a := range analytics {
		events := make([]string, len(a.Events))
		for i, event := range a.Events {
			events[i] = fmt.Sprintf("%q", event)
		}
		namespaceParts = append(namespaceParts, fmt.Sprintf("%s: [%s]", toCamelCase(a.Name), strings.Join(events, ", ")))
		sinks := make([]string, len(a.Sinks))
		for i, sink := range a.Sinks {
			if sink.Target != nil {
				sinks[i] = fmt.Sprintf("{ kind: %q, target: %s }", sink.Kind, exprToJS(sink.Target))
			} else {
				sinks[i] = fmt.Sprintf("{ kind: %q }", sink.Kind)
			}
		}
		sinkParts = append(sinkParts, fmt.Sprintf("%s: [%s]", toCamelCase(a.Name), strings.Join(sinks, ", ")))
	}
	fmt.Fprintf(&b, "export const analyticsNamespaces = { %s } as const;\n", strings.Join(namespaceParts, ", "))
	fmt.Fprintf(&b, "export const analyticsSinks = { %s } as const;\n", strings.Join(sinkParts, ", "))
	b.WriteString("export type AnalyticsNamespace = keyof typeof analyticsNamespaces;\n")
	b.WriteString("const analyticsBatchSize = 25;\n")
	b.WriteString("const analyticsFlushMs = 2000;\n")
	b.WriteString("const analyticsMaxRetries = 3;\n")
	b.WriteString("const analyticsQueues = new Map<string, Array<{ namespace: AnalyticsNamespace; event: string; payload: unknown; at: string }>>();\n")
	b.WriteString("const analyticsTimers = new Map<string, ReturnType<typeof setTimeout>>();\n\n")
	b.WriteString("async function sleep(ms: number): Promise<void> {\n  await new Promise((resolve) => setTimeout(resolve, ms));\n}\n\n")
	b.WriteString("async function sendAnalyticsBatch(target: string, batch: Array<{ namespace: AnalyticsNamespace; event: string; payload: unknown; at: string }>): Promise<void> {\n")
	b.WriteString("  let lastError: unknown;\n")
	b.WriteString("  for (let attempt = 0; attempt < analyticsMaxRetries; attempt++) {\n")
	b.WriteString("    try {\n")
	b.WriteString("      const response = await fetch(target, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ events: batch }) });\n")
	b.WriteString("      if (!response.ok) throw new Error(`Analytics sink failed: ${response.status}`);\n")
	b.WriteString("      return;\n")
	b.WriteString("    } catch (error) {\n")
	b.WriteString("      lastError = error;\n")
	b.WriteString("      await sleep((attempt + 1) * 500);\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n")
	b.WriteString("  throw lastError instanceof Error ? lastError : new Error(String(lastError));\n")
	b.WriteString("}\n\n")
	b.WriteString("async function flushAnalyticsTarget(target: string): Promise<void> {\n")
	b.WriteString("  const batch = analyticsQueues.get(target) ?? [];\n")
	b.WriteString("  if (batch.length === 0) return;\n")
	b.WriteString("  analyticsQueues.set(target, []);\n")
	b.WriteString("  const timer = analyticsTimers.get(target);\n")
	b.WriteString("  if (timer) { clearTimeout(timer); analyticsTimers.delete(target); }\n")
	b.WriteString("  await sendAnalyticsBatch(target, batch);\n")
	b.WriteString("}\n\n")
	b.WriteString("function queueAnalytics(target: string, item: { namespace: AnalyticsNamespace; event: string; payload: unknown; at: string }): void {\n")
	b.WriteString("  const queue = analyticsQueues.get(target) ?? [];\n")
	b.WriteString("  queue.push(item);\n")
	b.WriteString("  analyticsQueues.set(target, queue);\n")
	b.WriteString("  if (queue.length >= analyticsBatchSize) {\n")
	b.WriteString("    void flushAnalyticsTarget(target);\n")
	b.WriteString("    return;\n")
	b.WriteString("  }\n")
	b.WriteString("  if (!analyticsTimers.has(target)) {\n")
	b.WriteString("    analyticsTimers.set(target, setTimeout(() => { void flushAnalyticsTarget(target); }, analyticsFlushMs));\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")
	b.WriteString("export async function track(event: string, payload: unknown = {}): Promise<void> {\n")
	b.WriteString("  const namespaces = Object.entries(analyticsNamespaces).filter(([, events]) => (events as readonly string[]).includes(event)).map(([name]) => name as AnalyticsNamespace);\n")
	b.WriteString("  for (const namespace of namespaces) {\n")
	b.WriteString("    for (const sink of ((analyticsSinks as any)[namespace] ?? [])) {\n")
	b.WriteString("      switch (sink.kind) {\n")
	b.WriteString("        case 'console':\n")
	b.WriteString("          console.log(`[analytics:${namespace}] ${event}`, payload);\n")
	b.WriteString("          break;\n")
	b.WriteString("        case 'http':\n")
	b.WriteString("          queueAnalytics(String(sink.target), { namespace, event, payload, at: new Date().toISOString() });\n")
	b.WriteString("          break;\n")
	b.WriteString("      }\n")
	b.WriteString("    }\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return codegen.OutputFile{Path: "src/lib/analytics.ts", Content: []byte(b.String())}
}

func (g *Generator) genSaveMigrations(saves []*ast.SaveSchema) []codegen.OutputFile {
	var files []codegen.OutputFile
	var b strings.Builder
	b.WriteString(fileHeader(g.sourceFile))
	for _, save := range saves {
		imports := saveMigrationImports(save)
		for _, imp := range imports {
			fmt.Fprintf(&b, "import { %s } from %q;\n", imp.FuncName, imp.ModulePath)
		}
	}
	b.WriteString("\n")
	for _, save := range saves {
		name := toPascalCase(save.Name)
		versionField := toCamelCase(save.VersionField)
		fmt.Fprintf(&b, "export const %sSaveConfig = { model: %q, versionField: %q, latest: %d } as const;\n", toCamelCase(save.Name), save.Model, save.VersionField, save.Latest)
		fmt.Fprintf(&b, "export async function upgrade%sSave<T extends Record<string, any>>(save: T): Promise<T> {\n", name)
		b.WriteString("  let current: any = { ...save };\n")
		if save.Latest <= 1 {
			b.WriteString("  return current as T;\n")
			b.WriteString("}\n\n")
		} else {
			fmt.Fprintf(&b, "  let version = Number(current.%s ?? 1);\n", versionField)
			fmt.Fprintf(&b, "  while (version < %d) {\n", save.Latest)
			b.WriteString("    switch (version) {\n")
			for version := 1; version < save.Latest; version++ {
				fmt.Fprintf(&b, "      case %d:\n", version)
				fmt.Fprintf(&b, "        current = await migrate%sSaveFrom%dTo%d(current);\n", name, version, version+1)
				fmt.Fprintf(&b, "        version = %d;\n", version+1)
				fmt.Fprintf(&b, "        current.%s = %d;\n", versionField, version+1)
				b.WriteString("        break;\n")
			}
			b.WriteString("      default:\n        return current as T;\n")
			b.WriteString("    }\n")
			b.WriteString("  }\n")
			b.WriteString("  return current as T;\n")
			b.WriteString("}\n\n")
		}

		files = append(files, saveMigrationStubs(g.sourceFile, save)...)
	}
	files = append(files, codegen.OutputFile{Path: "src/lib/save-migrations.ts", Content: []byte(b.String())})
	return files
}

type saveMigrationImport struct {
	FuncName   string
	ModulePath string
}

func saveMigrationImports(save *ast.SaveSchema) []saveMigrationImport {
	if save.Latest <= 1 {
		return nil
	}
	byStep := map[string]*ast.SaveMigration{}
	for _, mig := range save.Migrations {
		byStep[fmt.Sprintf("%d->%d", mig.From, mig.To)] = mig
	}
	imports := make([]saveMigrationImport, 0, save.Latest-1)
	for version := 1; version < save.Latest; version++ {
		funcName := fmt.Sprintf("migrate%sSaveFrom%dTo%d", toPascalCase(save.Name), version, version+1)
		modulePath := fmt.Sprintf("../saves/%s.js", toKebabCase(save.Name))
		if mig := byStep[fmt.Sprintf("%d->%d", version, version+1)]; mig != nil && mig.Module != "" {
			modulePath = saveMigrationModuleImport(mig.Module)
		}
		imports = append(imports, saveMigrationImport{FuncName: funcName, ModulePath: modulePath})
	}
	return imports
}

func saveMigrationModuleImport(module string) string {
	if strings.HasPrefix(module, "./") {
		module = "../saves/" + strings.TrimPrefix(module, "./")
	}
	if !strings.HasSuffix(module, ".js") {
		module += ".js"
	}
	return module
}

func saveMigrationStubs(sourceFile string, save *ast.SaveSchema) []codegen.OutputFile {
	if save.Latest <= 1 {
		return []codegen.OutputFile{{Path: fmt.Sprintf("src/saves/%s.ts", toKebabCase(save.Name)), Content: []byte(fileHeader(sourceFile) + "export {};\n")}}
	}
	byModule := map[string][]string{}
	for version := 1; version < save.Latest; version++ {
		stepKey := fmt.Sprintf("%d->%d", version, version+1)
		funcName := fmt.Sprintf("migrate%sSaveFrom%dTo%d", toPascalCase(save.Name), version, version+1)
		modulePath := fmt.Sprintf("src/saves/%s.ts", toKebabCase(save.Name))
		for _, mig := range save.Migrations {
			if fmt.Sprintf("%d->%d", mig.From, mig.To) == stepKey && mig.Module != "" {
				modulePath = saveMigrationStubPath(mig.Module)
				break
			}
		}
		byModule[modulePath] = append(byModule[modulePath], funcName)
	}
	files := make([]codegen.OutputFile, 0, len(byModule))
	for path, funcs := range byModule {
		var stub strings.Builder
		fmt.Fprintf(&stub, "// Blueprint save migration implementation scaffold from %s.\n", sourceFile)
		stub.WriteString("// This file is user-owned; `bp build` will not overwrite it. Implement the migration functions below.\n\n")
		for _, fn := range funcs {
			fmt.Fprintf(&stub, "export async function %s(save: any): Promise<any> {\n", fn)
			stub.WriteString("  return save;\n")
			stub.WriteString("}\n\n")
		}
		files = append(files, codegen.OutputFile{
			Path:      path,
			Content:   []byte(stub.String()),
			UserOwned: true,
		})
	}
	return files
}

